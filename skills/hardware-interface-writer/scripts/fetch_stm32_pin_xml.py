@dataclass(frozen=True)
class PatternToken:
    raw: str
    choices: frozenset[str] | None = None
    wildcard: bool = False

    def matches(self, char: str) -> bool:
        if self.wildcard:
            return bool(WILDCARD_RE.fullmatch(char))
        if self.choices is not None:
            return char.upper() in self.choices
        return self.raw.upper() == char.upper()


def normalize_query(value: str) -> str:
    value = value.strip()
    if value.lower().endswith(".xml"):
        value = value[:-4]
    return "".join(ch for ch in value if ch.isalnum()).upper()


def stem_for(filename: str) -> str:
    return filename[:-4] if filename.lower().endswith(".xml") else filename


def expand_group(group: str) -> frozenset[str]:
    parts = [part.upper() for part in group.split("-") if part]
    if len(parts) == 2 and len(parts[0]) == len(parts[1]) == 1:
        start = ORDER_CODE_CHARS.find(parts[0])
        end = ORDER_CODE_CHARS.find(parts[1])
        if start != -1 and end != -1:
            lo, hi = sorted((start, end))
            return frozenset(ORDER_CODE_CHARS[lo : hi + 1])
    chars = set()
    for part in parts or [group.upper()]:
        chars.update(ch for ch in part if ch.isalnum())
    return frozenset(chars)


def parse_pattern(filename: str) -> tuple[PatternToken, ...]:
    stem = stem_for(filename)
    tokens: list[PatternToken] = []
    index = 0
    while index < len(stem):
        char = stem[index]
        if char == "(":
            end = stem.find(")", index + 1)
            if end == -1:
                tokens.append(PatternToken(char))
                index += 1
                continue
            tokens.append(PatternToken(stem[index : end + 1], choices=expand_group(stem[index + 1 : end])))
            index = end + 1
        elif char == "x":
            tokens.append(PatternToken(char, wildcard=True))
            index += 1
        else:
            tokens.append(PatternToken(char))
            index += 1
    return tuple(tokens)


_PATTERN_TOKENS = {name: parse_pattern(name) for name in ST_MCU_XML_NAMES}


def pattern_matches(filename: str, query: str) -> bool:
    tokens = _PATTERN_TOKENS[filename]
    return len(query) == len(tokens) and all(token.matches(char) for token, char in zip(tokens, query))


def prefix_compatible(filename: str, query: str) -> bool:
    tokens = _PATTERN_TOKENS[filename]
    return len(query) <= len(tokens) and all(token.matches(char) for token, char in zip(tokens, query))


def pattern_hint(filename: str) -> str:
    hint = []
    for token in _PATTERN_TOKENS[filename]:
        if token.wildcard:
            hint.append("0")
        elif token.choices is not None:
            ordered = [ch for ch in ORDER_CODE_CHARS if ch in token.choices]
            hint.append(ordered[0] if ordered else "0")
        else:
            hint.append(token.raw.upper())
    return "".join(hint)


def relevance(filename: str, query: str) -> tuple[int, float, int, str]:
    hint = pattern_hint(filename)
    prefix_bonus = 1000 if prefix_compatible(filename, query) else 0
    literal_stem = "".join(ch for ch in stem_for(filename).upper() if ch.isalnum())
    common_prefix = len(query) + len(hint)
    for idx, (left, right) in enumerate(zip(query, hint)):
        if left != right:
            common_prefix = idx
            break
    ratio = max(
        difflib.SequenceMatcher(None, query, hint).ratio(),
        difflib.SequenceMatcher(None, query, literal_stem).ratio(),
    )
    return (prefix_bonus + common_prefix, ratio, -abs(len(hint) - len(query)), filename)


def best_candidates(query: str, top: int) -> list[str]:
    scored = sorted(ST_MCU_XML_NAMES, key=lambda name: relevance(name, query), reverse=True)
    return scored[: max(top, 0)]


def source_url(filename: str) -> str:
    return f"{SOURCE_BASE_URL}/{filename}"


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def print_json(payload: dict[str, object]) -> None:
    print(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True))


def emit_candidates(args: argparse.Namespace, query: str, exact_matches: list[str]) -> int:
    candidates = exact_matches or best_candidates(query, args.top)
    status = "ambiguous" if exact_matches else "no_exact_match"
    payload = {
        "status": status,
        "input": args.mcu,
        "normalized_input": query,
        "message": "input did not uniquely identify one STM32 XML file",
        "candidates": candidates,
    }
    if args.json:
        print_json(payload)
    else:
        print(f"Input {args.mcu!r} did not uniquely identify one STM32 XML file.", file=sys.stderr)
        if candidates:
            print("Top candidates:", file=sys.stderr)
            for name in candidates:
                print(f"  {name}", file=sys.stderr)
        else:
            print("No candidates found in the built-in STM32_open_pin_data list.", file=sys.stderr)
        print("Re-run with a complete STM32 ordering code, including package and suffix.", file=sys.stderr)
    return 2


def handle_match(args: argparse.Namespace, query: str, match: str) -> int:
    url = source_url(match)
    output_dir = Path(args.output_dir)
    output_path = output_dir / match
    metadata_path = output_dir / f"{match}.source.json"

    if args.dry_run:
        payload = {
            "status": "matched",
            "input": args.mcu,
            "normalized_input": query,
            "match": match,
            "source_url": url,
            "output_path": str(output_path),
            "source_json_path": str(metadata_path),
            "dry_run": True,
            "would_download": not output_path.exists() or args.force,
            "exists": output_path.exists(),
        }
        if args.json:
            print_json(payload)
        else:
            print(f"Matched {match}")
            print(f"Dry run: would download {url}")
            print(f"Output: {output_path}")
        return 0

    if output_path.exists() and not args.force:
        payload = {
            "status": "exists",
            "input": args.mcu,
            "normalized_input": query,
            "match": match,
            "source_url": url,
            "output_path": str(output_path),
            "source_json_path": str(metadata_path),
            "dry_run": False,
            "downloaded": False,
            "message": "output already exists; use --force to overwrite",
        }
        if args.json:
            print_json(payload)
        else:
            print(f"Matched {match}")
            print(f"Already exists: {output_path}")
            print("Use --force to overwrite.")
        return 0

    try:
        with urllib.request.urlopen(url, timeout=60) as response:
            data = response.read()
    except (urllib.error.URLError, TimeoutError) as exc:
        payload = {
            "status": "download_error",
            "input": args.mcu,
            "match": match,
            "source_url": url,
            "error": str(exc),
        }
        if args.json:
            print_json(payload)
        else:
            print(f"Failed to download {url}: {exc}", file=sys.stderr)
        return 1

    output_dir.mkdir(parents=True, exist_ok=True)
    digest = sha256_bytes(data)
    output_path.write_bytes(data)
    metadata = {
        "input_mcu": args.mcu,
        "normalized_input": query,
        "matched_xml": match,
        "source_url": url,
        "downloaded_at": _dt.datetime.now(_dt.timezone.utc).isoformat(),
        "sha256": digest,
    }
    metadata_path.write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    payload = {
        "status": "downloaded",
        "input": args.mcu,
        "normalized_input": query,
        "match": match,
        "source_url": url,
        "output_path": str(output_path),
        "source_json_path": str(metadata_path),
        "sha256": digest,
        "dry_run": False,
        "downloaded": True,
    }
    if args.json:
        print_json(payload)
    else:
        print(f"Matched {match}")
        print(f"Downloaded: {output_path}")
        print(f"Metadata: {metadata_path}")
        print(f"SHA256: {digest}")
    return 0


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Fetch a matching STM32_open_pin_data MCU XML file for a concrete STM32 ordering code."
    )
    parser.add_argument("mcu", help="Concrete STM32 ordering code, for example STM32F103C8T6")
    parser.add_argument("--output-dir", default=str(Path("docs") / "mcu"), help="Directory for the XML and .source.json files")
    parser.add_argument("--top", type=int, default=5, help="Number of candidates to print for ambiguous input")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing XML and metadata file")
    parser.add_argument("--dry-run", action="store_true", help="Resolve the match without downloading or writing files")
    parser.add_argument("--json", action="store_true", help="Print machine-readable JSON")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    query = normalize_query(args.mcu)
    if not query:
        if args.json:
            print_json({"status": "invalid_input", "input": args.mcu, "message": "empty MCU code"})
        else:
            print("Empty MCU code.", file=sys.stderr)
        return 2

    exact_matches = [name for name in ST_MCU_XML_NAMES if pattern_matches(name, query)]
    if len(exact_matches) == 1:
        return handle_match(args, query, exact_matches[0])
    return emit_candidates(args, query, exact_matches)


if __name__ == "__main__":
    raise SystemExit(main())
